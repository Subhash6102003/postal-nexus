import http from 'k6/http';
import { check, sleep } from 'k6';

// k6 Load Test Configuration
export const options = {
  scenarios: {
    // Scenario 1: Sustained high-volume ingress (1,000 concurrent users)
    high_throughput_burst: {
      executor: 'ramping-vus',
      startVUs: 10,
      stages: [
        { duration: '30s', target: 200 },
        { duration: '1m', target: 1000 },
        { duration: '30s', target: 0 },
      ],
      gracefulRampDown: '10s',
    },
    // Scenario 2: Rate limit stress test (User attempting to exceed 5 req/min)
    rate_limit_enforcement: {
      executor: 'constant-vus',
      vus: 10,
      duration: '30s',
    },
  },
  thresholds: {
    http_req_duration: ['p(95)<150', 'p(99)<300'], // 95% of requests under 150ms
    http_req_failed: ['rate<0.05'], // Max 5% non-rate-limit errors
  },
};

const BASE_URL = __ENV.TARGET_URL || 'http://localhost:3000';

export default function () {
  // Generate a distinct virtual user ID for this VU
  const userId = `k6_user_${__VU}`;
  const requestId = `${Date.now()}-${__VU}-${__ITER}`;

  const payload = JSON.stringify({
    recipient: `test_${__VU}_${__ITER}@loadtest.local`,
    subject: `Load Test Message #${__ITER}`,
    body_text: `Test payload generated by virtual user ${userId}`,
    idempotency_key: `idem-${userId}-${__ITER}`,
  });

  const params = {
    headers: {
      'Content-Type': 'application/json',
      'X-User-Id': userId,
      'X-Correlation-ID': requestId,
    },
  };

  const res = http.post(`${BASE_URL}/api/v1/emails/send`, payload, params);

  // The first 5 requests from a single user within 1 minute should return 202
  // Subsequent requests from the same user should return 429
  if (res.status === 202) {
    check(res, {
      'status is 202 Accepted': (r) => r.status === 202,
      'response has requestId': (r) => JSON.parse(r.body).requestId !== undefined,
      'has X-RateLimit-Limit': (r) => r.headers['X-Ratelimit-Limit'] !== undefined,
    });
  } else if (res.status === 429) {
    check(res, {
      'status is 429 Too Many Requests': (r) => r.status === 429,
      'has Retry-After header': (r) => r.headers['Retry-After'] !== undefined,
      'X-RateLimit-Remaining is 0': (r) => r.headers['X-Ratelimit-Remaining'] === '0',
    });
  }

  sleep(0.5);
}
